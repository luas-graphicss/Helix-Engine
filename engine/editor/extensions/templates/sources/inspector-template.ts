export function inspectorTemplateSource(tab: string): string {
    return [
        'import helix from "helix"',
        '',
        'const editor = helix.editor',
        '',
        'if (editor) {',
        `${tab}editor.inspectors.register("altura-rapida", {`,
        `${tab}${tab}title: "Altura rápida",`,
        `${tab}${tab}kinds: ["mesh", "group"],`,
        `${tab}${tab}multiple: true,`,
        `${tab}${tab}onGui(ui, actors) {`,
        `${tab}${tab}${tab}const current = helix.transform.position(actors[0])[1]`,
        `${tab}${tab}${tab}const typed = ui.number("Altura", current, { step: 0.25 })`,
        `${tab}${tab}${tab}const grounded = ui.button("Apoiar no chão", { icon: "magnet" })`,
        `${tab}${tab}${tab}ui.label(\`\${actors.length} ator(es) nesta seção\`, { muted: true })`,
        `${tab}${tab}${tab}if (typed === current && !grounded) return`,
        `${tab}${tab}${tab}const height = grounded ? 0 : typed`,
        `${tab}${tab}${tab}const moves = actors.map((actor) => {`,
        `${tab}${tab}${tab}${tab}const position = helix.transform.position(actor)`,
        `${tab}${tab}${tab}${tab}return { actor, x: position[0], y: position[1], z: position[2] }`,
        `${tab}${tab}${tab}})`,
        `${tab}${tab}${tab}editor.history.execute({`,
        `${tab}${tab}${tab}${tab}label: "Mudar altura",`,
        `${tab}${tab}${tab}${tab}execute: () => moves.forEach((move) => helix.transform.setPosition(move.actor, [move.x, height, move.z])),`,
        `${tab}${tab}${tab}${tab}undo: () => moves.forEach((move) => helix.transform.setPosition(move.actor, [move.x, move.y, move.z])),`,
        `${tab}${tab}${tab}})`,
        `${tab}${tab}},`,
        `${tab}})`,
        '}',
        '',
    ].join('\n');
}
