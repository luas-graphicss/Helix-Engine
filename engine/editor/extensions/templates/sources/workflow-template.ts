export function workflowTemplateSource(tab: string): string {
    return [
        'import helix from "helix"',
        '',
        'const editor = helix.editor',
        '',
        'if (editor) {',
        `${tab}editor.workflows.register("revisar-cena", {`,
        `${tab}${tab}title: "Revisar cena",`,
        `${tab}${tab}description: "Confere os nomes das malhas e relata o resultado no console.",`,
        `${tab}${tab}icon: "workflow",`,
        `${tab}${tab}trigger: "projectSaved",`,
        `${tab}${tab}steps: [`,
        `${tab}${tab}${tab}{`,
        `${tab}${tab}${tab}${tab}title: "Contar atores",`,
        `${tab}${tab}${tab}${tab}run(step) {`,
        `${tab}${tab}${tab}${tab}${tab}step.data.total = helix.scene.count()`,
        `${tab}${tab}${tab}${tab}},`,
        `${tab}${tab}${tab}},`,
        `${tab}${tab}${tab}{`,
        `${tab}${tab}${tab}${tab}title: "Conferir nomes",`,
        `${tab}${tab}${tab}${tab}async run(step) {`,
        `${tab}${tab}${tab}${tab}${tab}const meshes = helix.scene.byKind("mesh")`,
        `${tab}${tab}${tab}${tab}${tab}let unnamed = 0`,
        `${tab}${tab}${tab}${tab}${tab}for (let index = 0; index < meshes.length; index++) {`,
        `${tab}${tab}${tab}${tab}${tab}${tab}if (step.cancelled) return`,
        `${tab}${tab}${tab}${tab}${tab}${tab}if (meshes[index].name.trim() === "") unnamed++`,
        `${tab}${tab}${tab}${tab}${tab}${tab}step.progress((index + 1) / meshes.length, meshes[index].name)`,
        `${tab}${tab}${tab}${tab}${tab}${tab}if (index % 50 === 49) await helix.time.waitFrames(1)`,
        `${tab}${tab}${tab}${tab}${tab}}`,
        `${tab}${tab}${tab}${tab}${tab}helix.log.info("Revisão", \`\${step.data.total} atores na cena, \${unnamed} malha(s) sem nome.\`)`,
        `${tab}${tab}${tab}${tab}},`,
        `${tab}${tab}${tab}},`,
        `${tab}${tab}],`,
        `${tab}})`,
        `${tab}editor.events.on("playModeChanged", (state) => {`,
        `${tab}${tab}helix.log.info("Extensão", \`Simulação: \${state}\`)`,
        `${tab}})`,
        '}',
        '',
    ].join('\n');
}
