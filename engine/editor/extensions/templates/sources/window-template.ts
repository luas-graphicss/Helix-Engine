export function windowTemplateSource(tab: string): string {
    return [
        'import helix from "helix"',
        '',
        'const editor = helix.editor',
        'const row = { name: "Cubo", count: 5, spacing: 2 }',
        '',
        'function createRow() {',
        `${tab}for (let index = 0; index < row.count; index++) {`,
        `${tab}${tab}const actor = helix.scene.spawnPrimitive("box", { name: \`\${row.name} \${index + 1}\` })`,
        `${tab}${tab}helix.transform.setPosition(actor, [index * row.spacing, 0.5, 0])`,
        `${tab}}`,
        '}',
        '',
        'if (editor) {',
        `${tab}const janela = editor.windows.register("fileira", {`,
        `${tab}${tab}title: "Fileira",`,
        `${tab}${tab}icon: "layout-grid",`,
        `${tab}${tab}area: "right",`,
        `${tab}${tab}onGui(ui) {`,
        `${tab}${tab}${tab}ui.heading("Fileira de atores")`,
        `${tab}${tab}${tab}row.name = ui.text("Nome", row.name)`,
        `${tab}${tab}${tab}row.count = ui.number("Quantidade", row.count, { min: 1, max: 50, step: 1 })`,
        `${tab}${tab}${tab}row.spacing = ui.slider("Espaçamento", row.spacing, 0.5, 10)`,
        `${tab}${tab}${tab}if (ui.button("Criar fileira", { variant: "primary", icon: "plus" })) createRow()`,
        `${tab}${tab}${tab}ui.label(\`\${helix.scene.count()} atores na cena\`, { muted: true })`,
        `${tab}${tab}},`,
        `${tab}})`,
        `${tab}janela.open()`,
        '}',
        '',
    ].join('\n');
}
