export function gizmoTemplateSource(tab: string): string {
    return [
        'import helix from "helix"',
        '',
        'const editor = helix.editor',
        '',
        'if (editor) {',
        `${tab}editor.gizmos.register("frente-do-ator", {`,
        `${tab}${tab}kinds: ["mesh", "light", "camera"],`,
        `${tab}${tab}when: "selected",`,
        `${tab}${tab}onDraw(draw, actor) {`,
        `${tab}${tab}${tab}draw.color("#ffd166")`,
        `${tab}${tab}${tab}draw.local(actor, () => {`,
        `${tab}${tab}${tab}${tab}draw.arrow([0, 0, 0], [0, 0, -2])`,
        `${tab}${tab}${tab}${tab}draw.circle([0, 0, 0], 1)`,
        `${tab}${tab}${tab}})`,
        `${tab}${tab}},`,
        `${tab}})`,
        `${tab}editor.gizmos.register("origem-da-cena", {`,
        `${tab}${tab}onDrawScene(draw) {`,
        `${tab}${tab}${tab}draw.color("#4cc9f0", 0.8)`,
        `${tab}${tab}${tab}draw.cross([0, 0, 0], 2)`,
        `${tab}${tab}${tab}draw.sphere([0, 0, 0], 0.25)`,
        `${tab}${tab}},`,
        `${tab}})`,
        '}',
        '',
    ].join('\n');
}
