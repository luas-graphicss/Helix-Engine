export function menuTemplateSource(tab: string): string {
    return [
        'import helix from "helix"',
        '',
        'const editor = helix.editor',
        '',
        'if (editor) {',
        `${tab}editor.menus.register("Ferramentas/Apoiar no chão", {`,
        `${tab}${tab}icon: "magnet",`,
        `${tab}${tab}shortcut: "Ctrl+Shift+G",`,
        `${tab}${tab}enabled: (target) => target.actors.length > 0,`,
        `${tab}${tab}run: (target) => {`,
        `${tab}${tab}${tab}for (const actor of target.actors) {`,
        `${tab}${tab}${tab}${tab}const position = helix.transform.position(actor)`,
        `${tab}${tab}${tab}${tab}helix.transform.setPosition(actor, [position[0], 0, position[2]])`,
        `${tab}${tab}${tab}}`,
        `${tab}${tab}},`,
        `${tab}})`,
        `${tab}editor.menus.register("Zerar rotação", {`,
        `${tab}${tab}location: "actor",`,
        `${tab}${tab}icon: "refresh",`,
        `${tab}${tab}run: (target) => {`,
        `${tab}${tab}${tab}for (const actor of target.actors) helix.transform.setRotation(actor, [0, 0, 0])`,
        `${tab}${tab}},`,
        `${tab}})`,
        '}',
        '',
    ].join('\n');
}
