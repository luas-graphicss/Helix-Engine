export function menuTemplateSource(tab: string): string {
    return [
        'import helix from "helix"',
        '',
        'const editor = helix.editor',
        '',
        'if (editor) {',
        `${tab}editor.menus.register("Ferramentas/Apoiar no chão", {`,
        `${tab}${tab}icon: "magnet",`,
        `${tab}${tab}shortcut: "Ctrl+Shift+G",`,
        `${tab}${tab}enabled: (target) => target.actors.length > 0,`,
        `${tab}${tab}run: (target) => {`,
        `${tab}${tab}${tab}const moves = target.actors.map((actor) => {`,
        `${tab}${tab}${tab}${tab}const position = helix.transform.position(actor)`,
        `${tab}${tab}${tab}${tab}return { actor, x: position[0], y: position[1], z: position[2] }`,
        `${tab}${tab}${tab}})`,
        `${tab}${tab}${tab}editor.history.execute({`,
        `${tab}${tab}${tab}${tab}label: "Apoiar no chão",`,
        `${tab}${tab}${tab}${tab}execute: () => moves.forEach((move) => helix.transform.setPosition(move.actor, [move.x, 0, move.z])),`,
        `${tab}${tab}${tab}${tab}undo: () => moves.forEach((move) => helix.transform.setPosition(move.actor, [move.x, move.y, move.z])),`,
        `${tab}${tab}${tab}})`,
        `${tab}${tab}},`,
        `${tab}})`,
        `${tab}editor.menus.register("Enquadrar e isolar", {`,
        `${tab}${tab}location: "actor",`,
        `${tab}${tab}icon: "target",`,
        `${tab}${tab}enabled: (target) => target.actor !== null,`,
        `${tab}${tab}run: (target) => {`,
        `${tab}${tab}${tab}if (!target.actor) return`,
        `${tab}${tab}${tab}editor.select(target.actor)`,
        `${tab}${tab}${tab}editor.viewport.frame(target.actor)`,
        `${tab}${tab}},`,
        `${tab}})`,
        '}',
        '',
    ].join('\n');
}
