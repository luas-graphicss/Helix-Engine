export function toolTemplateSource(tab: string): string {
    return [
        'import helix from "helix"',
        '',
        'const editor = helix.editor',
        'const stamp = { size: 1, count: 0, hovering: false, cursor: [0, 0, 0] }',
        '',
        'if (editor) {',
        `${tab}editor.tools.register("carimbo", {`,
        `${tab}${tab}title: "Carimbo de caixas",`,
        `${tab}${tab}icon: "box",`,
        `${tab}${tab}shortcut: "Shift+B",`,
        `${tab}${tab}cursor: "crosshair",`,
        `${tab}${tab}onPointerMove(event) {`,
        `${tab}${tab}${tab}stamp.hovering = event.point !== null`,
        `${tab}${tab}${tab}if (event.point) stamp.cursor = [event.point[0], event.point[1], event.point[2]]`,
        `${tab}${tab}},`,
        `${tab}${tab}onPointerDown(event) {`,
        `${tab}${tab}${tab}if (!event.point) return`,
        `${tab}${tab}${tab}const actor = helix.scene.spawnPrimitive("box", { name: \`Caixa \${++stamp.count}\` })`,
        `${tab}${tab}${tab}helix.transform.setScale(actor, stamp.size)`,
        `${tab}${tab}${tab}helix.transform.setPosition(actor, [event.point[0], event.point[1] + stamp.size / 2, event.point[2]])`,
        `${tab}${tab}},`,
        `${tab}${tab}onDraw(draw) {`,
        `${tab}${tab}${tab}if (!stamp.hovering) return`,
        `${tab}${tab}${tab}const [x, y, z] = stamp.cursor`,
        `${tab}${tab}${tab}draw.color("#4cc9f0")`,
        `${tab}${tab}${tab}draw.circle([x, y, z], stamp.size / 2)`,
        `${tab}${tab}${tab}draw.box([x, y + stamp.size / 2, z], stamp.size)`,
        `${tab}${tab}},`,
        `${tab}${tab}onGui(ui) {`,
        `${tab}${tab}${tab}stamp.size = ui.slider("Tamanho", stamp.size, 0.25, 5, { step: 0.25 })`,
        `${tab}${tab}${tab}ui.label(\`\${stamp.count} caixa(s) carimbada(s)\`, { muted: true })`,
        `${tab}${tab}},`,
        `${tab}})`,
        '}',
        '',
    ].join('\n');
}
