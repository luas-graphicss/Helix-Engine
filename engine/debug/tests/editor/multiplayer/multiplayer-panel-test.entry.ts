import { addMatchQueue } from '@/engine/editor/operations/multiplayer/matchmaking-queue-operations';
import { setMultiplayerEnabled, setRelayEnabled, updateMultiplayerSession } from '@/engine/editor/operations/multiplayer/multiplayer-settings-operations';
import { addNetworkObject, addNetworkVariable, canAddNetworkObject, setNetworkVariableKind, updateNetworkObject } from '@/engine/editor/operations/multiplayer/network-object-operations';
import { addRpc, updateRpc } from '@/engine/editor/operations/multiplayer/rpc-declaration-operations';
import { planSceneNetwork } from '@/engine/net/scene/scene-network-plan';
import { NETWORK_PRESETS } from '@/engine/net/transport/network-conditions';
import { applySimulatedConditions } from '@/engine/scripting/runtime/simulated-conditions';
import { engineSettings } from '@/engine/settings/engine-settings-store';
import { createCheckList } from '../../support/check-list';
import { IDLE_STATUS, LIVE_STATUS, createPanelStage, renderInspector, renderObjects, renderPanel, renderRpcs, renderServer, renderServices, renderTools } from './panel-stage';
const checks = createCheckList('Painel Multiplayer e seção Objeto de rede do Inspetor');
const DISABLED_NOTICE = 'O multiplayer está desligado nesta cena';
function includesAll(markup: string, parts: readonly string[]): boolean {
    return parts.every((part) => markup.includes(part));
}
function missing(markup: string, parts: readonly string[]): string {
    return parts.filter((part) => !markup.includes(part)).join(' | ');
}
engineSettings.adopt({});
const stage = createPanelStage();
const { scene, session, history } = stage;
const hero = scene.createEntity({ name: 'Heroi', kind: 'group' });
const sword = scene.createEntity({ name: 'Espada', kind: 'mesh' }, hero);
const crate = scene.createEntity({ name: 'Caixa', kind: 'mesh' });
const panelParts = ['Sessão', 'Serviços', 'Objetos', 'RPCs', 'Servidor', 'Ferramentas', 'Topologia', 'Sincronização', 'Sessões no servidor', 'Ao vivo'];
let panel = renderPanel(stage);
checks.check('o painel abre na aba Sessão com as seis abas', includesAll(panel, panelParts), missing(panel, panelParts));
checks.check('com o multiplayer desligado o painel avisa', panel.includes(DISABLED_NOTICE));
setMultiplayerEnabled(session, true);
panel = renderPanel(stage);
checks.check('ligar tira o aviso e põe a topologia no rodapé', !panel.includes(DISABLED_NOTICE) && panel.includes('Servidor dedicado · 20 Hz'));
checks.check('ligar o multiplayer é um passo desfazível', history.undoDepth === 1);
history.undo();
checks.check('desfazer devolve o painel ao estado desligado', !scene.multiplayer.enabled && renderPanel(stage).includes(DISABLED_NOTICE));
history.redo();
const serviceParts = ['Lobby', 'Matchmaking', 'Relay', 'Membros por lobby'];
let services = renderServices(stage);
checks.check('a aba Serviços mostra lobby, matchmaking e relay', scene.multiplayer.enabled && includesAll(services, serviceParts), missing(services, serviceParts));
addMatchQueue(session);
services = renderServices(stage);
const queueNames = scene.multiplayer.matchmaking.queues.map((queue) => queue.name);
checks.check('uma fila nova aparece com nome próprio', queueNames.length === 2 && new Set(queueNames).size === 2 && queueNames.every((name) => services.includes(`value="${name}"`)), queueNames.join(', '));
updateMultiplayerSession(session, { topology: 'relay' });
setRelayEnabled(session, false);
checks.check('jogador anfitrião sem relay ganha um aviso', renderServices(stage).includes('depende do relay'));
setRelayEnabled(session, true);
updateMultiplayerSession(session, { topology: 'dedicated' });
checks.check('sem RPCs a aba explica como declarar', renderRpcs(stage).includes('Nenhum RPC declarado'));
addRpc(session);
addRpc(session);
updateRpc(session, 'rpc2', { name: 'rpc' });
const rpcNames = scene.multiplayer.rpcs.map((rpc) => rpc.name);
const rpcs = renderRpcs(stage);
checks.check('RPCs declarados aparecem e os nomes não se repetem', rpcNames.length === 2 && new Set(rpcNames).size === 2 && rpcNames.every((name) => rpcs.includes(`value="${name}"`)), rpcNames.join(', '));
checks.check('sem objetos de rede a aba orienta o primeiro passo', renderObjects(stage).includes('Nenhum ator em rede ainda'));
stage.select(hero);
addNetworkObject(session, hero, 'player');
const objectParts = ['Heroi', 'Um por jogador', 'Dono', 'Este ator já é um objeto de rede'];
const objects = renderObjects(stage);
checks.check('o ator posto em rede entra na lista com modo e autoridade', includesAll(objects, objectParts), missing(objects, objectParts));
checks.check('um objeto de rede não pode conter outro', !canAddNetworkObject(sword));
const addSection = renderInspector(stage, crate);
checks.check('ator fora da rede ganha a seção Multiplayer no Inspetor', addSection.includes('Multiplayer') && !addSection.includes('Objeto de rede'));
checks.check('filho de um objeto de rede não recebe a seção', renderInspector(stage, sword) === '');
const inspectorParts = ['Objeto de rede', 'Posse e relevância', 'Variáveis de rede', 'Entrada', 'Autoridade', 'Vel. máxima'];
let inspector = renderInspector(stage, hero);
checks.check('objeto de rede mostra entrada, autoridade e as três seções', includesAll(inspector, inspectorParts), missing(inspector, inspectorParts));
addNetworkVariable(session, hero);
setNetworkVariableKind(session, hero, 0, 'boolean');
inspector = renderInspector(stage, hero);
checks.check('variável nova aparece com nome, tipo e valor inicial', includesAll(inspector, ['value="valor"', 'value="boolean" selected', 'aria-label="Valor inicial de valor"']));
const depthBeforeAuthority = history.undoDepth;
updateNetworkObject(session, hero, { authority: 'server' });
checks.check('com autoridade do servidor a velocidade máxima sai do Inspetor', !renderInspector(stage, hero).includes('Vel. máxima'));
history.undo();
checks.check('desfazer devolve a autoridade ao dono', history.undoDepth === depthBeforeAuthority && hero.networkObject?.authority === 'owner');
const { schema } = planSceneNetwork(scene);
const serverParts = ['Servidor dedicado', 'Ligar o servidor autoritativo', 'Exportar pacote do servidor', 'O que vai no pacote', schema, 'Teste de jogo', 'Simulado no editor', 'Inicie o teste de jogo com o servidor simulado'];
let server = renderServer(stage, IDLE_STATUS);
checks.check('a aba Servidor traz os passos, o pacote e o destino do teste', includesAll(server, serverParts), missing(server, serverParts));
const liveServerParts = ['Lobbies abertos', '1 min 5 s', 'principal', '2 de 16', 'tick 1950'];
server = renderServer(stage, LIVE_STATUS);
checks.check('com o teste rodando aparecem os números e as sessões do servidor', includesAll(server, liveServerParts), missing(server, liveServerParts));
engineSettings.set('simulation.net.server', 'hosted');
checks.check('hospedado sem endereço avisa que o teste cai no simulado', renderServer(stage, IDLE_STATUS).includes('Sem endereço do servidor'));
scene.scripting.server.url = 'wss://jogo.exemplo.com';
checks.check('hospedado com endereço mostra a rota da sessão', renderServer(stage, IDLE_STATUS).includes('wss://jogo.exemplo.com/mp/session/principal'));
engineSettings.set('simulation.net.server', 'simulated');
const toolParts = ['Rede simulada', 'Clientes de teste', 'Tráfego', 'Vale a partir do próximo teste de jogo', '0 de 8'];
let tools = renderTools(stage, IDLE_STATUS);
checks.check('a aba Ferramentas traz rede simulada, clientes de teste e tráfego', includesAll(tools, toolParts), missing(tools, toolParts));
applySimulatedConditions(session.scripts.multiplayer, NETWORK_PRESETS.find((preset) => preset.id === 'wifi')?.conditions ?? {});
const liveToolParts = ['value="wifi" selected', 'Aplicado ao vivo na sessão em andamento', '42 ms', '0.4%', '18.4 kb/s', '1 de 8'];
tools = renderTools(stage, LIVE_STATUS);
checks.check('com sessão ao vivo o perfil aplicado e o tráfego aparecem', includesAll(tools, liveToolParts), missing(tools, liveToolParts));
checks.check('no servidor hospedado a rede simulada avisa que não entra', renderTools(stage, { ...LIVE_STATUS, linkKind: 'hosted', server: null }).includes('a rede é a de verdade'));
checks.finish();
