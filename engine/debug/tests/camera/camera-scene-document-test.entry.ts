import { createMaterial } from '@/engine/core/scene/material';
import { Scene } from '@/engine/core/scene/scene';
import { createCameraSettings, normalizeCameraSettings } from '@/engine/camera/camera-settings';
import { MaterialLibrary } from '@/engine/materials/material-library';
import { deserializeScene } from '@/engine/project/scene-document/deserialize-scene';
import { serializeScene } from '@/engine/project/scene-document/serialize-scene';
import { createBox } from '@/engine/renderer/geometry/primitives';
import { createCheckList } from '../support/check-list';
const FOREGROUND_LAYER = 1;
const MAP_LAYER = 3;
const checks = createCheckList('Câmeras no documento da cena');
function buildScene(): Scene {
    const scene = new Scene('Teste');
    scene.layers.names[MAP_LAYER] = 'Mapa';
    const overlay = scene.createEntity({ name: 'weapon camera', kind: 'camera', camera: normalizeCameraSettings({ ...createCameraSettings(), role: 'overlay' }) });
    scene.createEntity({ name: 'main camera', kind: 'camera', camera: normalizeCameraSettings({ ...createCameraSettings(), projection: 'orthographic', orthographicSize: 9, overlays: [overlay.id] }) });
    const monitor = scene.createEntity({ name: 'monitor camera', kind: 'camera', camera: normalizeCameraSettings({ ...createCameraSettings(), target: 'texture' }) });
    scene.createEntity({ name: 'legacy camera', kind: 'camera' });
    const screen = createMaterial({ name: 'screen', baseColorMap: scene.cameraFeeds.ensure(monitor) });
    scene.createEntity({ name: 'screen', kind: 'mesh', mesh: createBox(), material: screen, layer: FOREGROUND_LAYER });
    scene.createEntity({ name: 'floor', kind: 'mesh', mesh: createBox() });
    return scene;
}
const source = buildScene();
const document = await serializeScene(source, { libraryDocumentForTerrainMaterial: () => null });
const savedFeed = document.json.textures.find((texture) => texture.cameraFeed !== undefined);
checks.check('a textura de câmera é salva como vínculo, sem imagem', savedFeed?.cameraFeed === source.cameraFeeds.ownerOf(source.cameraFeeds.list()[0]) && savedFeed.image === null && document.images.length === 0);
checks.check('a camada padrão não ocupa espaço no documento', document.json.root.children.find((entity) => entity.name === 'floor')?.layer === undefined);
const { scene, warnings } = await deserializeScene(document, { materials: new MaterialLibrary(() => undefined, null) });
const find = (name: string) => scene.entities.find((entity) => entity.name === name) ?? null;
const main = find('main camera');
const overlay = find('weapon camera');
const monitor = find('monitor camera');
const screen = find('screen');
checks.check('abrir a cena não gera avisos', warnings.length === 0, warnings.join(' | '));
checks.check('a projeção e o tamanho voltam', main?.camera?.projection === 'orthographic' && main.camera.orthographicSize === 9);
checks.check('a pilha volta apontando para a sobreposição', overlay !== null && main?.camera?.overlays.join() === String(overlay.id) && overlay.camera?.role === 'overlay');
checks.check('ator de câmera antigo continua sem componente', find('legacy camera')?.camera === null);
checks.check('a camada do ator volta', screen?.layer === FOREGROUND_LAYER && find('floor')?.layer === 0);
checks.check('os nomes das camadas voltam', scene.layers.names[MAP_LAYER] === 'Mapa' && scene.layers.names[0] === 'Padrão');
const feed = monitor ? scene.cameraFeeds.find(monitor.id) : null;
checks.check('o material volta ligado à textura viva da câmera', feed !== null && screen?.material?.baseColorMap === feed && feed.dynamic);
checks.finish();
