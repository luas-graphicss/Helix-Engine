import * as vec3 from '@/engine/core/math/vec3';
import { createDriveCommand, resolveDriveCommand } from '@/engine/vehicle/drivetrain/drive-command';
import { engineTorqueAt } from '@/engine/vehicle/drivetrain/engine-torque';
import { FIRST_GEAR, Gearbox, gearRatio, REVERSE_GEAR } from '@/engine/vehicle/drivetrain/gearbox';
import { createVehicleInput } from '@/engine/vehicle/input/vehicle-input';
import { ackermannAngle, steerTowards } from '@/engine/vehicle/steering/steering';
import { distributeSprungMass } from '@/engine/vehicle/suspension/sprung-mass';
import { suspensionForce } from '@/engine/vehicle/suspension/suspension-force';
import { createVehicleSettings, normalizeVehicleSettings, type VehicleSettings } from '@/engine/vehicle/vehicle-settings';
import { createWheelFrictionCurve, evaluateWheelFriction, normalizeWheelFrictionCurve } from '@/engine/vehicle/wheel/wheel-friction';
import { createWheelSettings, normalizeWheelSettings, type WheelSettings } from '@/engine/vehicle/wheel/wheel-settings';
import { createCheckList } from '../support/check-list';
const STEP = 1 / 60;
const GRAVITY = 9.81;
const CHASSIS_MASS = 1200;
const checks = createCheckList('Motor, câmbio, direção e suspensão do veículo');
const settings = createVehicleSettings();
function sum(values: readonly number[]): number {
    return values.reduce((total, value) => total + value, 0);
}
checks.near('marcha lenta entrega parte do torque', engineTorqueAt(settings, settings.idleRpm), settings.maxTorque * 0.6);
checks.near('pico de torque na rotação configurada', engineTorqueAt(settings, settings.peakRpm), settings.maxTorque);
checks.check('torque cai depois do pico', engineTorqueAt(settings, settings.maxRpm - 1) < settings.maxTorque && engineTorqueAt(settings, settings.maxRpm - 1) > settings.maxTorque * 0.69);
checks.near('corte de giro zera o torque', engineTorqueAt(settings, settings.maxRpm), 0);
checks.near('primeira marcha usa a relação configurada', gearRatio(settings, FIRST_GEAR), settings.firstGearRatio);
checks.near('última marcha usa a relação configurada', gearRatio(settings, settings.gearCount), settings.topGearRatio);
checks.check('as relações caem a cada marcha', [2, 3, 4, 5].every((gear) => gearRatio(settings, gear) < gearRatio(settings, gear - 1)));
checks.near('a ré inverte o sentido', gearRatio(settings, REVERSE_GEAR), -settings.reverseGearRatio);
checks.near('câmbio de uma marcha só usa a primeira relação', gearRatio(createVehicleSettings({ gearCount: 1 }), 3), settings.firstGearRatio);
const gearbox = new Gearbox();
const redlineShaftRpm = (settings.maxRpm * 0.95) / gearRatio(settings, FIRST_GEAR);
gearbox.shift(settings, redlineShaftRpm, STEP);
checks.check('sobe de marcha perto do corte de giro', gearbox.gear === 2);
gearbox.shift(settings, redlineShaftRpm * 4, STEP);
checks.check('espera a troca terminar antes de subir outra marcha', gearbox.gear === 2);
gearbox.shift(settings, redlineShaftRpm, 1);
checks.check('não reduz logo depois de subir', gearbox.gear === 2);
gearbox.shift(settings, 100, 1);
checks.check('reduz quando o giro cai', gearbox.gear === FIRST_GEAR);
gearbox.engageReverse();
gearbox.shift(settings, redlineShaftRpm * 4, 1);
checks.check('a ré não troca de marcha sozinha', gearbox.gear === REVERSE_GEAR);
gearbox.engageForward();
checks.check('engatar para frente volta à primeira', gearbox.gear === FIRST_GEAR);
const input = createVehicleInput();
const command = createDriveCommand();
input.throttle = 1;
resolveDriveCommand(command, input, 0);
checks.check('acelerar parado engata para frente', command.throttle === 1 && command.brake === 0 && !command.reverse);
resolveDriveCommand(command, input, -4);
checks.check('acelerar andando de ré freia antes', command.throttle === 0 && command.brake === 1);
input.throttle = -0.5;
resolveDriveCommand(command, input, 8);
checks.check('pedir ré em movimento freia', command.throttle === 0 && command.brake === 0.5 && !command.reverse);
resolveDriveCommand(command, input, 0);
checks.check('pedir ré parado engata a ré', command.throttle === 0.5 && command.reverse);
input.throttle = 0;
input.brake = 0.3;
input.handbrake = 1;
resolveDriveCommand(command, input, 0);
checks.check('sem acelerador mantém a marcha e repassa os freios', command.reverse && command.throttle === 0 && command.brake === 0.3 && command.handbrake === 1);
const curve = createWheelFrictionCurve({ extremumSlip: 0.2, extremumValue: 1, asymptoteSlip: 0.6, asymptoteValue: 0.5 });
checks.near('aderência cheia até o limite de escorregamento', evaluateWheelFriction(curve, 0.1), 1);
checks.near('aderência a meio caminho do deslizamento', evaluateWheelFriction(curve, -0.4), 0.75);
checks.near('aderência mínima deslizando', evaluateWheelFriction(curve, 3), 0.5);
checks.near('a rigidez escala a curva inteira', evaluateWheelFriction({ ...curve, stiffness: 2 }, 0.1), 2);
const repaired = normalizeWheelFrictionCurve({ extremumSlip: 0.5, asymptoteSlip: 0.1, extremumValue: Number.NaN, stiffness: 99 }, curve);
checks.check('curva inválida é corrigida ao abrir a cena', repaired.asymptoteSlip > repaired.extremumSlip && repaired.extremumValue === curve.extremumValue && repaired.stiffness === 4);
const corners = [vec3.create(0.8, 0, 1.3), vec3.create(-0.8, 0, 1.3), vec3.create(0.8, 0, -1.3), vec3.create(-0.8, 0, -1.3)];
checks.nearAll('rodas simétricas dividem a massa por igual', distributeSprungMass(corners, CHASSIS_MASS), [300, 300, 300, 300], 1e-2);
const noseHeavy = distributeSprungMass([vec3.create(0.8, 0, 1), vec3.create(-0.8, 0, 1), vec3.create(0.8, 0, -1.6), vec3.create(-0.8, 0, -1.6)], CHASSIS_MASS);
checks.near('a massa distribuída soma a do chassi', sum(noseHeavy), CHASSIS_MASS, 1e-2);
checks.near('o eixo mais perto do centro de massa carrega mais', noseHeavy[0] + noseHeavy[1], (CHASSIS_MASS * 1.6) / 2.6, 0.5);
const sixWheels = distributeSprungMass([...corners, vec3.create(0.8, 0, -2.4), vec3.create(-0.8, 0, -2.4)], CHASSIS_MASS);
checks.check('veículo de seis rodas mantém todas com carga', sixWheels.every((mass) => mass > 0) && Math.abs(sum(sixWheels) - CHASSIS_MASS) < 1e-2);
const inline = distributeSprungMass([vec3.create(0, 0, 0.7), vec3.create(0, 0, -0.7)], 200);
checks.nearAll('duas rodas em linha dividem a massa', inline, [100, 100], 1e-2);
checks.nearAll('uma roda só carrega tudo', distributeSprungMass([vec3.create(0.3, 0, 0.2)], 80), [80], 1e-3);
checks.check('veículo sem rodas não distribui massa', distributeSprungMass([], CHASSIS_MASS).length === 0);
const wheel = createWheelSettings({ suspensionTravel: 0.2, suspensionFrequency: 2, suspensionDamping: 0.5 });
const sprungMass = 300;
const springRate = sprungMass * (2 * Math.PI * 2) ** 2;
checks.near('em repouso a mola sustenta o peso da roda', suspensionForce({ sprungMass, compression: 0, compressionSpeed: 0 }, wheel, GRAVITY, STEP), sprungMass * GRAVITY, 1e-6);
checks.near('comprimir soma a força da mola', suspensionForce({ sprungMass, compression: 0.05, compressionSpeed: 0 }, wheel, GRAVITY, STEP), sprungMass * GRAVITY + springRate * 0.05, 1e-6);
checks.near('a suspensão nunca puxa o chassi para baixo', suspensionForce({ sprungMass, compression: -0.1, compressionSpeed: -5 }, wheel, GRAVITY, STEP), 0);
checks.check('o batente endurece a mola no fim do curso', suspensionForce({ sprungMass, compression: 0.15, compressionSpeed: 0 }, wheel, GRAVITY, STEP) > sprungMass * GRAVITY + springRate * 0.15);
const stiffDamper: WheelSettings = { ...wheel, suspensionDamping: 2, suspensionFrequency: 10 };
checks.check('o amortecedor não inverte a velocidade num passo', suspensionForce({ sprungMass, compression: 0, compressionSpeed: 1 }, stiffDamper, 0, STEP) <= sprungMass / STEP + 1e-6);
checks.near('o volante gira na velocidade configurada', steerTowards(0, 1, 0, settings, 0.1), settings.steerSpeed * 0.1);
checks.near('o volante para no ângulo máximo', steerTowards(0, 1, 0, settings, 10), settings.maxSteerAngle);
checks.near('em alta velocidade o ângulo máximo diminui', steerTowards(0, -1, 80, settings, 10), -settings.maxSteerAngle * settings.highSpeedSteering);
const centerAngle = 0.3;
const innerAngle = ackermannAngle(centerAngle, -0.8, 2.6, 1);
const outerAngle = ackermannAngle(centerAngle, 0.8, 2.6, 1);
checks.check('na curva à direita a roda de dentro vira mais', innerAngle > centerAngle && outerAngle < centerAngle && outerAngle > 0);
checks.near('sem Ackermann as rodas viram iguais', ackermannAngle(centerAngle, -0.8, 2.6, 0), centerAngle);
checks.near('reto continua reto', ackermannAngle(0, -0.8, 2.6, 1), 0);
checks.near('curva à esquerda espelha a da direita', ackermannAngle(-centerAngle, 0.8, 2.6, 1), -innerAngle, 1e-6);
const broken = { ...createVehicleSettings(), control: 'autopilot', gearCount: 3.6, maxTorque: -50, idleRpm: 2500, peakRpm: 1000, maxRpm: 1200, firstGearRatio: 1, topGearRatio: 4, brakeTorque: Number.NaN } as unknown as VehicleSettings;
const fixed = normalizeVehicleSettings(broken);
checks.check('controle desconhecido volta ao padrão', fixed.control === 'player');
checks.check('número de marchas vira inteiro', fixed.gearCount === 4);
checks.check('valores fora da faixa são limitados', fixed.maxTorque === 1 && fixed.brakeTorque === settings.brakeTorque);
checks.check('as rotações ficam em ordem', fixed.idleRpm < fixed.peakRpm && fixed.peakRpm < fixed.maxRpm);
checks.check('a última marcha nunca é mais curta que a primeira', fixed.topGearRatio <= fixed.firstGearRatio);
const partialWheel = normalizeWheelSettings({ radius: 99, mass: Number.NaN, steering: true } as unknown as WheelSettings);
checks.check('roda incompleta recebe os padrões', partialWheel.radius === 3 && partialWheel.mass === createWheelSettings().mass && partialWheel.steering && !partialWheel.driven && partialWheel.forwardFriction.extremumValue === createWheelSettings().forwardFriction.extremumValue);
checks.finish();
