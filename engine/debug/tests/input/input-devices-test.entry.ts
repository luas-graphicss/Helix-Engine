import { resolveControl, resolvedControlKind } from '@/engine/input/controls/control-descriptor';
import { describeControlPath } from '@/engine/input/controls/control-labels';
import { formatControlPath, MAX_CONTROL_PATH_LENGTH, parseControlPath } from '@/engine/input/controls/control-path';
import type { CustomDeviceLayout } from '@/engine/input/controls/custom-layout';
import { GAMEPAD_CONTROLS, LEFT_HAND } from '@/engine/input/controls/device-layouts';
import { createCustomDevice } from '@/engine/input/devices/custom-device';
import { DeviceRegistry, type DeviceChange } from '@/engine/input/devices/device-registry';
import { InputDevice } from '@/engine/input/devices/input-device';
import type { SourceContext } from '@/engine/input/devices/sources/device-source';
import { GamepadSource, type GamepadButtonLike, type GamepadLike } from '@/engine/input/devices/sources/gamepad-source';
import { XRControllerSource, type XRSessionLike } from '@/engine/input/devices/sources/xr-controller-source';
import { createCheckList } from '../support/check-list';
const STANDARD_BUTTON_COUNT = 17;
const SOUTH_BUTTON = 0;
const DPAD_LEFT_BUTTON = 14;
const checks = createCheckList('Dispositivos de entrada');
function buttons(count: number, pressed: readonly number[]): GamepadButtonLike[] {
    const list: GamepadButtonLike[] = [];
    for (let index = 0; index < count; index++)
        list.push({ pressed: pressed.includes(index), value: pressed.includes(index) ? 1 : 0 });
    return list;
}
function contextFor(registry: DeviceRegistry): SourceContext {
    return { registry, signal: new AbortController().signal, surface: null, acceptsKeyboard: () => true };
}
const stickPath = parseControlPath('<Gamepad>/leftStick/x');
checks.check('caminho separa o layout do controle', stickPath?.layout === 'Gamepad' && stickPath.control === 'leftStick/x' && stickPath.usage === null);
const handPath = parseControlPath('<XRController>{LeftHand}/trigger');
checks.check('caminho lê a mão do controle VR', handPath?.usage === LEFT_HAND && handPath.control === 'trigger');
checks.check('texto sem layout não é um caminho', parseControlPath('KeyW') === null);
checks.check('caminho acima do limite é recusado', parseControlPath(`<Keyboard>/${'K'.repeat(MAX_CONTROL_PATH_LENGTH)}`) === null);
checks.check('caminho formatado volta ao mesmo texto', formatControlPath('XRController', 'trigger', LEFT_HAND) === '<XRController>{LeftHand}/trigger');
const stickUp = resolveControl(GAMEPAD_CONTROLS, 'leftStick/up');
const stickAxis = resolveControl(GAMEPAD_CONTROLS, 'leftStick/x');
const stick = resolveControl(GAMEPAD_CONTROLS, 'leftStick');
checks.check('direção do analógico vale como botão', stickUp !== null && resolvedControlKind(stickUp) === 'button');
checks.check('componente do analógico vale como eixo', stickAxis !== null && resolvedControlKind(stickAxis) === 'axis');
checks.check('analógico inteiro vale como vetor', stick !== null && resolvedControlKind(stick) === 'vector2');
checks.check('controle desconhecido não resolve', resolveControl(GAMEPAD_CONTROLS, 'turbo') === null);
const spaceLabel = describeControlPath('<Keyboard>/Space', []);
checks.check('rótulo traduz dispositivo e tecla', spaceLabel?.device === 'Teclado' && spaceLabel.control === 'Espaço');
const device = new InputDevice({ id: 'probe', layout: 'Gamepad', name: 'Probe', controls: GAMEPAD_CONTROLS });
device.write('leftTrigger', 0.1);
checks.check('valor fraco não conta como uso do dispositivo', device.activity === 0);
device.write('leftTrigger', 0.9);
checks.check('valor forte conta como uso do dispositivo', device.activity === 1);
device.writeVector('rightStick', -0.5, 0.25);
checks.near('vetor grava a metade esquerda', device.read('rightStick/left'), 0.5);
checks.near('vetor zera a metade oposta', device.read('rightStick/right'), 0);
device.release();
checks.near('soltar zera os controles', device.read('leftTrigger'), 0);
const registry = new DeviceRegistry();
const changes: string[] = [];
registry.onChange((change: DeviceChange, changed) => changes.push(`${change}:${changed.id}`));
let pads: (GamepadLike | null)[] = [{ index: 0, id: 'Pad', mapping: 'standard', connected: true, axes: [0.5, -0.75, 0.03, 0.02], buttons: buttons(STANDARD_BUTTON_COUNT, [SOUTH_BUTTON, DPAD_LEFT_BUTTON]) }];
const gamepads = new GamepadSource(() => pads);
gamepads.attach(contextFor(registry));
gamepads.poll();
const pad = registry.find('gamepad:0');
checks.check('gamepad padrão entra como Gamepad', pad?.layout === 'Gamepad' && changes.includes('added:gamepad:0'));
checks.near('botão inferior pressionado', pad?.read('buttonSouth') ?? 0, 1);
checks.near('analógico esquerdo em X', pad?.read('leftStick/x') ?? 0, 0.5);
checks.near('analógico esquerdo sobe com o eixo invertido', pad?.read('leftStick/up') ?? 0, 0.75);
checks.near('ruído do analógico parado é descartado', pad?.read('rightStick/x') ?? 1, 0);
checks.near('direcional esquerdo vira vetor', pad?.read('dpad/x') ?? 0, -1);
pads = [null, { index: 1, id: 'Flight Stick', mapping: '', connected: true, axes: [0.4, 0, 0.9], buttons: buttons(4, [3]) }];
gamepads.poll();
const flightStick = registry.find('gamepad:1');
checks.check('gamepad desconectado sai do registro', registry.find('gamepad:0') === null && changes.includes('removed:gamepad:0'));
checks.check('mapeamento fora do padrão entra como Joystick', flightStick?.layout === 'Joystick');
checks.near('joystick expõe eixos numerados', flightStick?.read('axis2') ?? 0, 0.9);
checks.near('joystick expõe botões numerados', flightStick?.read('button3') ?? 0, 1);
checks.near('joystick expõe o manche', flightStick?.read('stick/x') ?? 0, 0.4);
const xr = new XRControllerSource();
const session: XRSessionLike = { inputSources: [{ handedness: 'left', gamepad: { axes: [0, 0, 0.6, -0.4], buttons: [{ pressed: false, value: 0.8 }, { pressed: true, value: 1 }] } }, { handedness: 'none', gamepad: null }] };
xr.attach(contextFor(registry));
xr.connect(session);
xr.poll();
const leftHand = registry.find('xr:left');
checks.check('controle VR carrega a mão como uso', leftHand?.layout === 'XRController' && leftHand.usages.includes(LEFT_HAND));
checks.near('gatilho VR analógico', leftHand?.read('trigger') ?? 0, 0.8);
checks.near('punho VR pressionado', leftHand?.read('grip') ?? 0, 1);
checks.near('analógico VR em X', leftHand?.read('thumbstick/x') ?? 0, 0.6);
checks.near('analógico VR em Y invertido', leftHand?.read('thumbstick/y') ?? 0, 0.4);
xr.connect(null);
xr.poll();
checks.check('controle VR sai quando a sessão termina', registry.find('xr:left') === null);
const danceMat: CustomDeviceLayout = { name: 'DanceMat', controls: [{ id: 'up', kind: 'button' }, { id: 'pressure', kind: 'axis' }] };
const mat = createCustomDevice(danceMat);
registry.add(mat);
mat.write('up', 1);
checks.check('dispositivo customizado entra com o próprio layout', registry.find('custom:DanceMat') === mat && mat.read('up') === 1);
checks.check('rótulo de dispositivo customizado usa o nome do layout', describeControlPath('<DanceMat>/pressure', [danceMat])?.device === 'DanceMat');
registry.add(mat);
checks.check('registrar o mesmo dispositivo duas vezes não duplica', registry.all.filter((candidate) => candidate === mat).length === 1);
checks.finish();
