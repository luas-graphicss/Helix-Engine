import { addAction, addBinding, addCustomControl, addCustomDevice, setCompositePartPath, updateBinding } from '@/engine/input/actions/asset-edits';
import { createDefaultInputAsset, GAMEPAD_SCHEME, KEYBOARD_MOUSE_SCHEME } from '@/engine/input/actions/default-input-asset';
import { createAction, createBinding, createCompositeBinding } from '@/engine/input/actions/input-factories';
import type { ActionState } from '@/engine/input/runtime/action-state';
import { InputSystem } from '@/engine/input/runtime/input-system';
import { createCheckList } from '../support/check-list';
import { advance, createGamepad, createKeyboard, createMouse, FRAME, recordSignals, requireAction } from './input-test-devices';
const checks = createCheckList('Ações de entrada');
const asset = createDefaultInputAsset();
const system = new InputSystem(asset);
const keyboard = createKeyboard();
const mouse = createMouse();
const gamepad = createGamepad(0);
system.devices.add(keyboard);
system.devices.add(mouse);
system.devices.add(gamepad);
function action(path: string): ActionState {
    return requireAction(system.actions.find(path), path);
}
const announced: string[] = [];
system.onAction((state, signal) => announced.push(`${state.path}:${signal}`));
const jump = action('Gameplay/Jump');
const jumpSignals = recordSignals(jump);
system.update(FRAME);
checks.check('ação parada fica em espera', jump.phase === 'waiting' && !jump.isPressed);
checks.check('ação com nome único é achada sem o mapa', system.actions.find('Jump') === jump);
keyboard.write('Space', 1);
system.update(FRAME);
checks.check('botão pressionado inicia e executa no mesmo quadro', jumpSignals.join(',') === 'started,performed' && jump.isPressed && jump.pressedFrame === system.frame);
checks.near('botão pressionado vale 1', jump.value.x, 1);
checks.check('ação lembra o dispositivo que a acionou', jump.device === keyboard);
checks.check('o sistema anuncia os eventos de qualquer ação', announced.join(',') === 'Gameplay/Jump:started,Gameplay/Jump:performed');
system.update(FRAME);
checks.check('botão segurado não repete eventos', jumpSignals.length === 2);
keyboard.write('Space', 0);
system.update(FRAME);
checks.check('soltar o botão cancela', jumpSignals.join(',') === 'started,performed,canceled' && jump.releasedFrame === system.frame && jump.phase === 'canceled');
system.update(FRAME);
checks.check('ação volta à espera depois de cancelar', jump.phase === 'waiting');
const move = action('Gameplay/Move');
const moveSignals = recordSignals(move);
keyboard.write('KeyW', 1);
system.update(FRAME);
checks.nearAll('W move para frente', [move.value.x, move.value.y], [0, 1]);
keyboard.write('KeyD', 1);
system.update(FRAME);
checks.nearAll('diagonal do composto é normalizada', [move.value.x, move.value.y], [Math.SQRT1_2, Math.SQRT1_2]);
checks.check('vetor executa a cada mudança de valor', moveSignals.join(',') === 'started,performed,performed');
system.update(FRAME);
checks.check('vetor parado no mesmo valor não repete', moveSignals.length === 3);
keyboard.write('KeyW', 0);
keyboard.write('KeyD', 0);
system.update(FRAME);
checks.check('vetor zerado cancela', moveSignals[moveSignals.length - 1] === 'canceled');
gamepad.writeVector('leftStick', 0.1, 0);
system.update(FRAME);
checks.near('analógico dentro da zona morta não move', move.value.x, 0);
gamepad.writeVector('leftStick', 0.575, 0);
system.update(FRAME);
checks.near('analógico fora da zona morta é reescalado', move.value.x, 0.5);
keyboard.write('KeyW', 1);
system.update(FRAME);
checks.check('o vínculo mais forte conduz a ação', move.value.y === 1 && move.device === keyboard);
keyboard.write('KeyW', 0);
gamepad.writeVector('leftStick', 0, 0);
system.update(FRAME);
const look = action('Gameplay/Look');
mouse.writeVector('delta', 30, -10);
system.update(FRAME);
checks.nearAll('movimento do mouse é escalado', [look.value.x, look.value.y], [3, -1]);
mouse.writeVector('delta', 0, 0);
system.update(FRAME);
const fire = action('Gameplay/Fire');
gamepad.write('rightTrigger', 0.4);
system.update(FRAME);
checks.check('gatilho abaixo do ponto de pressão não dispara', !fire.isPressed);
gamepad.write('rightTrigger', 0.6);
system.update(FRAME);
checks.check('gatilho acima do ponto de pressão dispara', fire.isPressed);
gamepad.write('rightTrigger', 0.45);
system.update(FRAME);
checks.check('gatilho segura até cair abaixo do ponto de soltura', fire.isPressed);
gamepad.write('rightTrigger', 0.3);
system.update(FRAME);
checks.check('gatilho solta abaixo do ponto de soltura', !fire.isPressed);
gamepad.write('rightTrigger', 0);
Object.assign(asset, updateBinding(asset, 'gameplay.interact.keyboard', { interaction: { kind: 'hold', duration: 0.5 } }));
const interact = action('Gameplay/Interact');
const interactSignals = recordSignals(interact);
keyboard.write('KeyE', 1);
system.update(FRAME);
checks.check('segurar inicia sem executar', interactSignals.join(',') === 'started');
advance(system, 0.6);
checks.check('segurar executa depois da duração', interactSignals.join(',') === 'started,performed');
keyboard.write('KeyE', 0);
system.update(FRAME);
checks.check('soltar depois de segurar cancela', interactSignals.join(',') === 'started,performed,canceled');
interactSignals.length = 0;
keyboard.write('KeyE', 1);
system.update(FRAME);
keyboard.write('KeyE', 0);
system.update(FRAME);
checks.check('soltar antes da duração cancela sem executar', interactSignals.join(',') === 'started,canceled');
Object.assign(asset, updateBinding(asset, 'gameplay.sprint.keyboard', { interaction: { kind: 'tap', duration: 0.2 } }));
const sprint = action('Gameplay/Sprint');
const sprintSignals = recordSignals(sprint);
keyboard.write('ShiftLeft', 1);
system.update(FRAME);
keyboard.write('ShiftLeft', 0);
system.update(FRAME);
checks.check('toque rápido executa ao soltar', sprintSignals.join(',') === 'started,performed');
sprintSignals.length = 0;
keyboard.write('ShiftLeft', 1);
advance(system, 0.4);
checks.check('toque demorado cancela', sprintSignals.join(',') === 'started,canceled');
keyboard.write('ShiftLeft', 0);
system.update(FRAME);
checks.check('soltar um toque já cancelado não emite nada', sprintSignals.length === 2);
keyboard.write('Space', 1);
system.update(FRAME);
jumpSignals.length = 0;
system.actions.disable('gameplay');
checks.check('desativar o mapa cancela as ações pressionadas', jumpSignals.join(',') === 'canceled' && !jump.isPressed);
system.update(FRAME);
checks.check('mapa desativado ignora os controles', !jump.isPressed);
system.actions.enable('gameplay');
system.update(FRAME);
checks.check('mapa reativado volta a ler os controles', jump.isPressed);
keyboard.write('Space', 0);
system.update(FRAME);
const schemes: string[] = [];
system.onSchemeChanged((scheme) => schemes.push(scheme.id));
gamepad.write('buttonSouth', 1);
system.update(FRAME);
keyboard.write('KeyA', 1);
system.update(FRAME);
checks.check('esquema atual segue o último dispositivo usado', schemes.join(',') === `${GAMEPAD_SCHEME},${KEYBOARD_MOUSE_SCHEME}` && system.currentScheme?.id === KEYBOARD_MOUSE_SCHEME && system.lastUsedDevice === keyboard);
gamepad.write('buttonSouth', 0);
keyboard.write('KeyA', 0);
system.update(FRAME);
Object.assign(asset, addBinding(asset, 'gameplay.jump', createBinding('<Keyboard>/KeyJ', [KEYBOARD_MOUSE_SCHEME])));
keyboard.write('KeyJ', 1);
system.update(FRAME);
checks.check('vínculo adicionado ao ativo vale no quadro seguinte', jump.isPressed);
keyboard.write('KeyJ', 0);
system.update(FRAME);
const throttleKeys = createCompositeBinding('axis1d');
const throttleAction = createAction('Throttle', 'axis');
Object.assign(asset, addBinding(addAction(asset, 'gameplay', throttleAction), throttleAction.id, throttleKeys));
Object.assign(asset, setCompositePartPath(setCompositePartPath(asset, throttleKeys.id, 'negative', '<Keyboard>/KeyZ'), throttleKeys.id, 'positive', '<Keyboard>/KeyX'));
system.update(FRAME);
const throttle = action('Gameplay/Throttle');
keyboard.write('KeyZ', 1);
system.update(FRAME);
checks.near('parte negativa do eixo composto', throttle.value.x, -1);
keyboard.write('KeyX', 1);
system.update(FRAME);
checks.near('partes opostas do eixo se anulam', throttle.value.x, 0);
keyboard.write('KeyZ', 0);
keyboard.write('KeyX', 0);
Object.assign(asset, addCustomControl(addCustomDevice(asset, 'DanceMat'), 'DanceMat', { id: 'up', kind: 'button' }));
Object.assign(asset, addBinding(asset, 'gameplay.jump', createBinding('<DanceMat>/up')));
system.update(FRAME);
const mat = system.customDevice('DanceMat');
mat?.write('up', 1);
system.update(FRAME);
checks.check('dispositivo customizado aciona ações pelo caminho do layout', mat !== null && jump.isPressed && jump.device === mat);
checks.finish();
