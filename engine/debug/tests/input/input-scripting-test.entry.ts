import { Scene } from '@/engine/core/scene/scene';
import { countBindings } from '@/engine/input/actions/asset-queries';
import { addCustomControl, addCustomDevice } from '@/engine/input/actions/asset-edits';
import { GAMEPAD_SCHEME } from '@/engine/input/actions/default-input-asset';
import { normalizeInputAsset } from '@/engine/input/actions/normalize-input-asset';
import { LiveInputSystem } from '@/engine/input/runtime/live-input-system';
import { toPlain } from '@/engine/project/scene-document/plain-data';
import { API_MANIFEST } from '@/engine/scripting/api-manifest';
import { createInputSystemApi } from '@/engine/scripting/api/input-system';
import { EventBus } from '@/engine/scripting/runtime/event-bus';
import type { RuntimeHost } from '@/engine/scripting/runtime/runtime-host';
import { createCheckList } from '../support/check-list';
import { createGamepad, createKeyboard, FRAME } from './input-test-devices';
const INPUT_SYSTEM_ROOTS = ['findAction', 'map', 'maps', 'rebind', 'overrides', 'devices', 'schemes', 'players'];
const checks = createCheckList('Sistema de entrada nos scripts');
function hasMember(root: unknown, path: string): boolean {
    let current = root;
    for (const part of path.split('.')) {
        if (typeof current !== 'object' || current === null || !(part in current))
            return false;
        current = (current as Record<string, unknown>)[part];
    }
    return true;
}
const scene = new Scene('Arena');
Object.assign(scene.input, addCustomControl(addCustomDevice(scene.input, 'DanceMat'), 'DanceMat', { id: 'up', kind: 'button' }));
checks.check('cena nova nasce com os mapas padrão', scene.input.maps.map((map) => map.name).join(',') === 'Gameplay,UI');
checks.check('o ativo da cena sobrevive à gravação', JSON.stringify(normalizeInputAsset(toPlain(scene.input, 'input'))) === JSON.stringify(scene.input));
checks.check('cena antiga sem ativo recebe o padrão', countBindings(normalizeInputAsset(undefined)) > 0);
const live = new LiveInputSystem(scene.input);
const { system } = live;
const disposers = new Set<() => void>();
const host = { bus: new EventBus({ invoke: (_owner, _phase, run) => run() }), inputSystem: live, disposers, current: null } as unknown as RuntimeHost;
const api = createInputSystemApi(host);
const keyboard = createKeyboard();
const padA = createGamepad(0);
const padB = createGamepad(1);
for (const device of [keyboard, padA, padB])
    system.devices.add(device);
const manifest = API_MANIFEST.find((namespace) => namespace.name === 'input');
const promised = manifest?.members.filter((member) => INPUT_SYSTEM_ROOTS.includes(member.split('.')[0])) ?? [];
checks.check('a API entrega cada membro que o manifesto promete', promised.length > INPUT_SYSTEM_ROOTS.length && promised.every((member) => hasMember(api, member)), promised.filter((member) => !hasMember(api, member)).join(', '));
const jump = api.map('Gameplay').action('Jump');
const performed: unknown[] = [];
const stop = jump.onPerformed((event: unknown) => performed.push(event));
system.update(FRAME);
keyboard.write('Space', 1);
system.update(FRAME);
checks.check('callback do script recebe a ação executada', performed.length === 1 && hasMember(performed[0], 'action') && jump.down && jump.pressed && jump.value === 1);
checks.check('a ação informa o dispositivo que a acionou', jump.device?.id === 'keyboard');
keyboard.write('Space', 0);
system.update(FRAME);
checks.check('a ação informa quando foi solta', jump.released && !jump.down);
stop();
keyboard.write('Space', 1);
system.update(FRAME);
keyboard.write('Space', 0);
system.update(FRAME);
checks.check('callback removido não é mais chamado', performed.length === 1);
checks.check('ação inexistente devolve null em findAction', api.findAction('Gameplay/Fly') === null);
checks.throws('mapa inexistente explica quais existem', () => api.map('Cutscene'), 'Gameplay, UI');
checks.throws('ação inexistente no mapa é recusada', () => api.map('UI').action('Jump'), 'não existe');
const menu = api.map('UI');
menu.enableOnly();
checks.check('enableOnly deixa só um mapa ativo', menu.enabled && !api.map('Gameplay').enabled);
api.map('Gameplay').enable();
const rebound: string[] = [];
api.rebind('Gameplay/Jump', { binding: 0, onComplete: (path: string) => rebound.push(path) });
keyboard.write('KeyJ', 1);
system.update(FRAME);
keyboard.write('KeyJ', 0);
system.update(FRAME);
checks.check('revinculação grava a troca e avisa o script', rebound.join(',') === '<Keyboard>/KeyJ' && jump.bindings.includes('<Keyboard>/KeyJ') && api.overrides.count === 1);
checks.throws('troca manual recusa caminho inválido', () => api.overrides.set('Gameplay/Jump', 'tecla J'), 'caminho de controle');
jump.resetBindings();
checks.check('resetBindings desfaz as trocas da ação', api.overrides.count === 0 && jump.bindings.includes('<Keyboard>/Space'));
const mat = api.devices.custom('DanceMat');
mat.set('up', 1);
checks.near('dispositivo customizado recebe valores do script', mat.read('up'), 1);
checks.throws('dispositivo físico recusa valores do script', () => api.devices.find('keyboard')?.set('Space', 1), 'dispositivo físico');
checks.throws('controle fora do layout customizado é recusado', () => mat.set('down', 1), 'não é um controle');
const joined: unknown[] = [];
api.players.onJoined((event: unknown) => joined.push(event));
const first = api.players.join({ scheme: GAMEPAD_SCHEME });
const second = api.players.join({ scheme: 'Gamepad' });
checks.check('jogadores entram com o esquema pedido', first?.index === 0 && second?.index === 1 && first.scheme === 'Gamepad' && joined.length === 2 && api.players.count === 2);
checks.throws('esquema inexistente lista os esquemas da cena', () => api.players.join({ scheme: 'Telepatia' }), 'Teclado e mouse');
padB.write('buttonSouth', 1);
system.update(FRAME);
checks.check('a ação de um jogador lê só o controle dele', second?.findAction('Gameplay/Jump')?.down === true && first?.findAction('Gameplay/Jump')?.down === false);
padB.write('buttonSouth', 0);
second?.leave();
checks.check('sair remove o jogador da lista', api.players.count === 1 && second?.joined === false);
for (const dispose of disposers)
    dispose();
keyboard.write('Space', 1);
system.update(FRAME);
checks.check('os repasses ao barramento saem quando o runtime para', disposers.size > 0 && performed.length === 1);
checks.finish();
