import { createDefaultInputAsset } from '@/engine/input/actions/default-input-asset';
import type { InputActionType } from '@/engine/input/actions/input-asset';
import { RebindListener, type RebindOutcome, type RebindRequest } from '@/engine/input/rebinding/rebind-listener';
import { InputSystem } from '@/engine/input/runtime/input-system';
import { createCheckList } from '../support/check-list';
import { createGamepad, createKeyboard, createMouse, createRightHand, FRAME, requireAction } from './input-test-devices';
const checks = createCheckList('Revinculação de controles');
const keyboard = createKeyboard();
const gamepad = createGamepad(0);
const mouse = createMouse();
const rightHand = createRightHand();
const devices = [keyboard, gamepad, mouse, rightHand];
function listen(expected: InputActionType, options: Partial<RebindRequest> = {}): RebindListener {
    return new RebindListener({ expected, devices: () => devices, ...options });
}
function pathOf(outcome: RebindOutcome | null): string | null {
    return outcome?.status === 'completed' ? outcome.path : null;
}
keyboard.write('anyKey', 1);
keyboard.write('KeyK', 1);
const heldAtStart = listen('button');
checks.check('controle já pressionado no início é ignorado', heldAtStart.update(FRAME) === null);
keyboard.write('KeyK', 0);
keyboard.write('anyKey', 0);
heldAtStart.update(FRAME);
keyboard.write('KeyK', 1);
keyboard.write('anyKey', 1);
checks.check('a escuta espera o controle ser solto', heldAtStart.update(FRAME) === null);
keyboard.write('KeyK', 0);
keyboard.write('anyKey', 0);
checks.check('tecla capturada vira o caminho do teclado', pathOf(heldAtStart.update(FRAME)) === '<Keyboard>/KeyK');
const canceled = listen('button');
keyboard.write('Escape', 1);
checks.check('Esc pressionado ainda não encerra', canceled.update(FRAME) === null);
keyboard.write('Escape', 0);
checks.check('soltar Esc cancela a escuta', canceled.update(FRAME)?.status === 'canceled');
const expiring = listen('button', { timeout: 1 });
checks.check('escuta segue antes do tempo limite', expiring.update(0.6) === null);
checks.check('escuta expira no tempo limite', expiring.update(0.6)?.status === 'timedOut');
const wholeStick = listen('vector2');
gamepad.write('buttonSouth', 1);
checks.check('botão não serve para uma ação de vetor', wholeStick.update(FRAME) === null);
gamepad.write('buttonSouth', 0);
gamepad.writeVector('leftStick', 0.9, 0);
wholeStick.update(FRAME);
gamepad.writeVector('leftStick', 0, 0);
checks.check('analógico movido vira o vetor inteiro', pathOf(wholeStick.update(FRAME)) === '<Gamepad>/leftStick');
const stickAxis = listen('axis');
gamepad.writeVector('leftStick', 0, -0.8);
stickAxis.update(FRAME);
gamepad.writeVector('leftStick', 0, 0);
checks.check('ação de eixo recebe o componente do analógico', pathOf(stickAxis.update(FRAME)) === '<Gamepad>/leftStick/y');
const stickDirection = listen('button');
gamepad.writeVector('leftStick', 0, 0.9);
stickDirection.update(FRAME);
gamepad.writeVector('leftStick', 0, 0);
checks.check('ação de botão recebe a direção do analógico', pathOf(stickDirection.update(FRAME)) === '<Gamepad>/leftStick/up');
const pointerLook = listen('vector2');
mouse.writeVector('position', 300, 200);
mouse.writeVector('delta', 40, 0);
checks.check('movimento curto do mouse não é capturado', pointerLook.update(FRAME) === null);
mouse.writeVector('delta', 50, 0);
pointerLook.update(FRAME);
mouse.writeVector('delta', 45, 0);
checks.check('movimento longo do mouse vira o vetor de movimento', pathOf(pointerLook.update(FRAME)) === '<Mouse>/delta');
mouse.writeVector('delta', 0, 0);
const handTrigger = listen('button');
rightHand.write('trigger', 1);
handTrigger.update(FRAME);
rightHand.write('trigger', 0);
checks.check('controle VR grava a mão no caminho', pathOf(handTrigger.update(FRAME)) === '<XRController>{RightHand}/trigger');
const withoutMouse = listen('button', { excludedLayouts: ['Mouse'] });
mouse.write('leftButton', 1);
withoutMouse.update(FRAME);
mouse.write('leftButton', 0);
checks.check('layout excluído não é capturado', withoutMouse.update(FRAME) === null);
const system = new InputSystem(createDefaultInputAsset());
const player = createKeyboard();
system.devices.add(player);
const jumpPath = 'Gameplay/Jump';
const movePath = 'Gameplay/Move';
const jump = requireAction(system.actions.find(jumpPath), jumpPath);
const move = requireAction(system.actions.find(movePath), movePath);
const { overrides } = system.actions;
overrides.set('gameplay.jump.keyboard', null, '<Keyboard>/KeyJ');
player.write('Space', 1);
system.update(FRAME);
checks.check('controle original deixa de valer depois da troca', !jump.isPressed);
player.write('Space', 0);
player.write('KeyJ', 1);
system.update(FRAME);
checks.check('controle novo passa a valer', jump.isPressed);
player.write('KeyJ', 0);
overrides.set('gameplay.move.wasd', 'up', '<Keyboard>/KeyI');
player.write('KeyI', 1);
system.update(FRAME);
checks.near('parte de composto aceita troca', move.value.y, 1);
player.write('KeyI', 0);
const saved: unknown = JSON.parse(JSON.stringify(overrides.toRecord()));
overrides.clear();
player.write('Space', 1);
system.update(FRAME);
checks.check('limpar as trocas restaura o controle original', jump.isPressed && overrides.size === 0);
player.write('Space', 0);
overrides.load(saved);
player.write('KeyJ', 1);
system.update(FRAME);
checks.check('trocas salvas voltam ao carregar', jump.isPressed && overrides.size === 2);
player.write('KeyJ', 0);
overrides.remove('gameplay.move.wasd');
checks.check('remover as trocas de um vínculo leva as partes', overrides.size === 1 && overrides.pathOf('gameplay.move.wasd', 'up') === undefined);
overrides.load({ 'gameplay.jump.keyboard': 'sem caminho', 'gameplay.fire.mouse': 7 });
checks.check('trocas inválidas não são carregadas', overrides.size === 0);
system.update(FRAME);
const outcomes: RebindOutcome[] = [];
system.startRebind({ expected: 'button' }, (outcome) => outcomes.push(outcome));
player.write('Space', 1);
system.update(FRAME);
checks.check('ações ficam suspensas durante a escuta', !jump.isPressed && system.isRebinding);
player.write('Space', 0);
system.update(FRAME);
checks.check('a escuta do sistema entrega o caminho capturado', pathOf(outcomes[0] ?? null) === '<Keyboard>/Space' && !system.isRebinding);
const cancel = system.startRebind({ expected: 'button' }, (outcome) => outcomes.push(outcome));
cancel();
checks.check('cancelar a escuta avisa quem pediu', outcomes[1]?.status === 'canceled' && !system.isRebinding);
checks.finish();
