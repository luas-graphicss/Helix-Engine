import type { ExecutorFactory } from '@/engine/jobs/executors/job-executor';
import type { JobPriority } from '@/engine/jobs/scheduling/job-queue';
import { createJobSettings } from '@/engine/jobs/settings/job-settings';
import { JobCancelledError, JobFailedError, JobTimeoutError } from '@/engine/jobs/system/job-errors';
import { createCheckList } from '../support/check-list';
import { NEVER_ENDING, createTestJobSystem, failureOf, nextTurn } from './job-test-system';
const checks = createCheckList('Sistema de jobs');
const messageOf = (error: unknown): string => (error instanceof Error ? error.message : '');
const jobs = createTestJobSystem(3);
const sum = await jobs.schedule<number>(jobs.program('(input) => input.a + input.b'), { a: 2, b: 3 }, { name: 'sum' });
checks.check('o job devolve o resultado calculado na thread', sum === 5);
checks.check('o job recebe a matemática da engine em job.math', (await jobs.schedule<number>(jobs.program('(input, job) => job.math.clamp(input, 0, 1)'), 7)) === 1);
const original = { values: [1, 2, 3] };
const grown = await jobs.schedule<number>(jobs.program('(input) => { input.values.push(4); return input.values.length; }'), original);
checks.check('o input chega copiado e o original fica intacto', grown === 4 && original.values.length === 3);
const awaited = await jobs.schedule<string>(jobs.program('async (input) => { await Promise.resolve(); return input.toUpperCase(); }'), 'pronto');
checks.check('job assíncrono é aguardado até terminar', awaited === 'PRONTO');
const samples = new Float32Array([1, 2, 3]);
const doubled = await jobs.schedule<Float32Array>(jobs.program('(input) => input.samples.map((sample) => sample * 2)'), { samples }, { transfer: [samples.buffer] });
checks.check('buffers transferidos mudam de dono e o resultado volta inteiro', samples.byteLength === 0 && Array.from(doubled).join(',') === '2,4,6');
const broken = jobs.schedule(jobs.program('() => { throw new Error("sem munição"); }'), null, { name: 'reload' });
const brokenError = await failureOf(broken);
checks.check('erro do job rejeita o handle com o nome e a mensagem', brokenError instanceof JobFailedError && brokenError.message.includes('reload') && brokenError.message.includes('sem munição') && broken.status === 'failed');
checks.check('variável capturada de fora ganha explicação', messageOf(await failureOf(jobs.schedule(jobs.program('() => outsideCounter + 1'), null))).includes('variáveis de fora'));
checks.check('helix não é alcançável de dentro do job', messageOf(await failureOf(jobs.schedule(jobs.program('() => helix.scene.count()'), null))).includes('helix não existe dentro de um job'));
checks.check('resultado não clonável é recusado com explicação', messageOf(await failureOf(jobs.schedule(jobs.program('() => () => 1'), null))).includes('dados clonáveis'));
checks.throws('código inválido é recusado antes de ir para a fila', () => jobs.program('() => {'), 'não pôde ser compilado');
checks.throws('código que não é função é recusado', () => jobs.program('42'), 'precisa ser uma função');
const single = createTestJobSystem(1);
const quick = single.program('() => 1');
const finished: string[] = [];
const track = (name: string, priority: JobPriority) => single.schedule(quick, null, { name, priority }).done.then(() => finished.push(name));
await Promise.all([track('blocker', 'normal'), track('low', 'low'), track('normal', 'normal'), track('high', 'high')]);
checks.check('a fila atende primeiro a prioridade mais alta', finished.join(',') === 'blocker,high,normal,low', finished.join(','));
const chain: string[] = [];
const hold = single.schedule(quick, null, { name: 'hold' });
const first = single.schedule(quick, null, { name: 'first', priority: 'low' });
const second = single.schedule(quick, null, { name: 'second', priority: 'high', dependsOn: [first] });
checks.check('job com dependência começa em espera', second.status === 'waiting' && first.status === 'queued' && hold.status === 'running');
await Promise.all([first.done.then(() => chain.push('first')), second.done.then(() => chain.push('second'))]);
checks.check('dependência roda antes mesmo com prioridade menor', chain.join(',') === 'first,second' && second.status === 'completed');
const failing = single.schedule(single.program('() => { throw new Error("falhou de propósito"); }'), null, { name: 'failing' });
const dependent = single.schedule(quick, null, { name: 'dependent', dependsOn: [failing] });
const [failingError, dependentError] = await Promise.all([failureOf(failing), failureOf(dependent)]);
checks.check('falha da dependência cancela quem esperava por ela', failingError instanceof JobFailedError && dependentError instanceof JobCancelledError && dependentError.message.includes('failing') && dependent.status === 'cancelled');
checks.throws('handle de outro sistema não serve de dependência', () => jobs.schedule(jobs.program('() => 1'), null, { dependsOn: [hold] }), 'por este sistema');
const executions = single.createBuffer('int32', 1);
const countRun = single.program('(input, job) => { job.output[0] += 1; }');
const occupied = single.schedule(quick, null, { name: 'occupied' });
const skipped = single.schedule(countRun, null, { name: 'skipped', output: executions });
const skippedFailure = failureOf(skipped);
skipped.cancel();
await occupied;
checks.check('job cancelado na fila nunca roda', (await skippedFailure) instanceof JobCancelledError && skipped.status === 'cancelled' && executions[0] === 0);
await single.schedule(countRun, null, { output: executions });
checks.check('saída em memória compartilhada é escrita no lugar', executions.buffer instanceof SharedArrayBuffer && executions[0] === 1);
const stuck = single.schedule(single.program(NEVER_ENDING), null, { name: 'stuck', timeoutMs: 0 });
await nextTurn();
const stuckFailure = failureOf(stuck);
const wasRunning = stuck.status === 'running';
const [busyThread] = single.snapshot().threads;
checks.check('o retrato mostra o job em andamento e o tempo ocupado da thread', busyThread.job?.name === 'stuck' && busyThread.busyMs > 0);
stuck.cancel();
checks.check('cancelar um job em execução rejeita o handle', wasRunning && (await stuckFailure) instanceof JobCancelledError);
checks.check('a thread volta a atender depois do cancelamento', (await single.schedule<number>(quick, null)) === 1);
const slow = single.schedule(single.program(NEVER_ENDING), null, { name: 'slow', timeoutMs: 20 });
const slowError = await failureOf(slow);
checks.check('job além do tempo limite falha e libera a thread', slowError instanceof JobTimeoutError && slow.status === 'failed' && single.snapshot().totals.timedOut === 1 && (await single.schedule<number>(quick, null)) === 1);
const limited = createTestJobSystem(1);
limited.configure({ ...createJobSettings(), maxQueued: 256 });
const one = limited.program('() => 1');
const accepted = [];
for (let index = 0; index < 256; index++)
    accepted.push(limited.schedule<number>(one, null));
checks.throws('fila cheia recusa novos jobs', () => limited.schedule(one, null), 'fila de jobs está cheia');
await Promise.all(accepted);
checks.check('a fila volta a aceitar depois de esvaziar', (await limited.schedule<number>(one, null)) === 1);
const endless = single.schedule(single.program(NEVER_ENDING), null, { timeoutMs: 0 });
const pending = [endless, single.schedule(quick, null), single.schedule(quick, null, { dependsOn: [endless] })];
const pendingFailures = Promise.all(pending.map(failureOf));
await nextTurn();
single.cancelAll();
const stopped = single.snapshot();
checks.check('cancelAll encerra jobs em execução, na fila e em espera', (await pendingFailures).every((error) => error instanceof JobCancelledError) && stopped.running === 0 && stopped.queued === 0 && stopped.waiting === 0);
const snapshot = jobs.snapshot();
checks.check('o retrato informa threads, modo e totais', snapshot.mode === 'threads' && snapshot.threadCount === 3 && snapshot.threads.length === 3 && snapshot.sharedMemory && snapshot.totals.completed >= 5 && snapshot.totals.failed >= 4);
checks.check('o histórico guarda thread e tempos de cada job', snapshot.history.length === snapshot.totals.completed + snapshot.totals.failed && snapshot.history.every((record) => record.thread !== null && record.startedAt !== null && record.queuedAt <= record.startedAt && record.startedAt <= record.finishedAt));
jobs.clearHistory();
checks.check('limpar o histórico zera registros e totais', jobs.snapshot().history.length === 0 && jobs.snapshot().totals.scheduled === 0);
const manual = createTestJobSystem(8);
manual.configure({ ...createJobSettings(), threads: 2 });
checks.check('quantidade manual de threads vale sobre a automática', manual.threadCount === 2);
manual.configure({ ...createJobSettings(), enabled: false });
checks.check('threads desligadas rodam os jobs na thread principal', manual.threadCount === 1 && manual.snapshot().mode === 'inline' && (await manual.schedule<number>(manual.program('() => 9'), null)) === 9);
const reasons: string[] = [];
const blockedSpawn: ExecutorFactory = () => {
    throw new Error('workers bloqueados');
};
const blocked = createTestJobSystem(2, blockedSpawn, (reason) => reasons.push(reason));
const rescued = await blocked.schedule<number>(blocked.program('() => 5'), null);
checks.check('sem conseguir criar threads o job roda na principal', rescued === 5 && reasons.join().includes('workers bloqueados') && blocked.snapshot().mode === 'inline' && blocked.threadCount === 1);
const crashingSpawn: ExecutorFactory = () => ({ kind: 'worker', run: () => Promise.reject(new Error('worker não carregou')), terminate: () => undefined });
const crashing = createTestJobSystem(2, crashingSpawn, (reason) => reasons.push(reason));
const recovered = await crashing.schedule<number>(crashing.program('() => 6'), null);
checks.check('thread que nunca funcionou devolve o job para a principal', recovered === 6 && reasons.join().includes('worker não carregou') && crashing.snapshot().mode === 'inline');
for (const system of [jobs, single, limited, manual, blocked, crashing])
    system.dispose();
checks.finish();
