import { MAX_BATCHES, resolveBatchSize, splitIntoBatches } from '@/engine/jobs/scheduling/batch-ranges';
import { JobCancelledError, JobFailedError } from '@/engine/jobs/system/job-errors';
import { createCheckList } from '../support/check-list';
import { NEVER_ENDING, createTestJobSystem, failureOf, nextTurn } from './job-test-system';
const ITEMS = 1000;
const checks = createCheckList('parallelFor do sistema de jobs');
const ranges = splitIntoBatches(10, 4);
checks.check('os lotes cobrem a contagem sem sobrar nem repetir', ranges.map((range) => `${range.index}:${range.start}-${range.end}`).join(' ') === '0:0-4 1:4-8 2:8-10');
checks.check('contagem vazia não gera lotes', splitIntoBatches(0, 4).length === 0);
checks.check('o lote automático divide a carga entre as threads', resolveBatchSize(ITEMS, undefined, 5) === 50 && resolveBatchSize(3, undefined, 8) === 1);
checks.check('lote pequeno demais é ampliado até o limite de lotes', splitIntoBatches(MAX_BATCHES * 10, resolveBatchSize(MAX_BATCHES * 10, 1, 4)).length === MAX_BATCHES);
const jobs = createTestJobSystem(3);
const sizes = await jobs.parallelFor<number>(ITEMS, jobs.program('(input, job) => job.end - job.start'), null, { name: 'sizes' });
checks.check('cada lote roda uma vez e os resultados voltam na ordem', sizes.length === 12 && sizes.reduce((total, size) => total + size, 0) === ITEMS);
const indexes = await jobs.parallelFor<number>(8, jobs.program('(input, job) => job.index'), null, { batchSize: 2 });
checks.check('batchSize define o tamanho de cada lote', indexes.join(',') === '0,1,2,3');
const threads = new Set(jobs.snapshot().history.map((record) => record.thread));
checks.check('os lotes se espalham pelas threads', threads.size === 3);
checks.check('o histórico identifica o lote de cada execução', jobs.snapshot().history.some((record) => record.name === 'sizes' && record.batch?.index === 11 && record.batch.count === 12));
const fillScaled = jobs.program('(input, job) => { for (let item = job.start; item < job.end; item++) job.output[item - job.start] = item * input.scale; }');
const copied = new Float32Array(ITEMS);
await jobs.parallelFor(ITEMS, fillScaled, { scale: 0.5 }, { output: copied });
checks.check('saída comum recebe a fatia de cada lote no lugar certo', copied.every((value, item) => value === item * 0.5));
const shared = jobs.createBuffer('float32', ITEMS * 2);
const fillPairs = jobs.program('(input, job) => { for (let item = job.start; item < job.end; item++) { const offset = (item - job.start) * 2; job.output[offset] = item; job.output[offset + 1] = item * input.scale; } }');
await jobs.parallelFor(ITEMS, fillPairs, { scale: 3 }, { output: shared, stride: 2 });
let pairsMatch = shared.buffer instanceof SharedArrayBuffer;
for (let item = 0; item < ITEMS; item++)
    pairsMatch &&= shared[item * 2] === item && shared[item * 2 + 1] === item * 3;
checks.check('saída compartilhada com stride é escrita direto pelas threads', pairsMatch);
checks.check('contagem zero resolve com lista vazia', (await jobs.parallelFor(0, fillScaled, null)).length === 0);
checks.throws('contagem negativa é recusada', () => jobs.parallelFor(-1, fillScaled, null), 'inteiro não negativo');
checks.throws('saída menor que a contagem é recusada', () => jobs.parallelFor(ITEMS, fillPairs, null, { output: copied, stride: 2 }), 'pedem 2000');
checks.throws('batchSize inválido é recusado', () => jobs.parallelFor(ITEMS, fillScaled, null, { batchSize: 0 }), 'batchSize');
const flawed = jobs.parallelFor(9, jobs.program('(input, job) => { if (job.index === 1) throw new Error("lote ruim"); return job.index; }'), null, { name: 'flawed', batchSize: 3 });
const flawedError = await failureOf(flawed);
checks.check('falha em um lote rejeita o job inteiro', flawedError instanceof JobFailedError && flawedError.message.includes('lote ruim') && flawed.status === 'failed');
const endless = jobs.parallelFor(6, jobs.program(NEVER_ENDING), null, { name: 'endless', batchSize: 1, timeoutMs: 0 });
const endlessFailure = failureOf(endless);
await nextTurn();
const statusBeforeCancel = endless.status;
endless.cancel();
const afterCancel = jobs.snapshot();
checks.check('cancelar o job encerra todos os lotes', statusBeforeCancel === 'running' && (await endlessFailure) instanceof JobCancelledError && endless.status === 'cancelled' && afterCancel.running === 0 && afterCancel.queued === 0);
const single = createTestJobSystem(1);
const order: string[] = [];
const group = single.parallelFor(4, single.program('(input, job) => job.index'), null, { name: 'group', batchSize: 1, priority: 'low' });
const after = single.schedule(single.program('() => 1'), null, { name: 'after', priority: 'high', dependsOn: [group] });
const startedWaiting = after.status === 'waiting';
await Promise.all([group.done.then(() => order.push('group')), after.done.then(() => order.push('after'))]);
checks.check('job que depende de um parallelFor espera todos os lotes', startedWaiting && order.join(',') === 'group,after');
jobs.dispose();
single.dispose();
checks.finish();
