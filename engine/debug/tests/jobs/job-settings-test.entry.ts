import { MaterialLibrary } from '@/engine/materials/material-library';
import { Scene } from '@/engine/core/scene/scene';
import { AUTOMATIC_THREADS, MAX_JOB_THREADS, automaticThreadCount, createJobSettings, normalizeJobSettings, resolveThreadCount, resolveTimeoutMs, type JobSettings } from '@/engine/jobs/settings/job-settings';
import { deserializeScene } from '@/engine/project/scene-document/deserialize-scene';
import { serializeScene } from '@/engine/project/scene-document/serialize-scene';
import { createCheckList } from '../support/check-list';
const checks = createCheckList('Configuração do sistema de jobs');
const defaults = createJobSettings();
checks.check('cena nova usa threads automáticas com limite de tempo', defaults.enabled && defaults.threads === AUTOMATIC_THREADS && defaults.timeoutSeconds === 10 && defaults.maxQueued === 4096);
checks.check('a contagem automática deixa um núcleo para o jogo', automaticThreadCount(8) === 7 && automaticThreadCount(1) === 1 && automaticThreadCount(Number.NaN) === 1);
checks.check('a contagem automática respeita o máximo de threads', automaticThreadCount(128) === MAX_JOB_THREADS);
checks.check('quantidade manual vale sobre os núcleos do aparelho', resolveThreadCount({ ...defaults, threads: 3 }, 16) === 3 && resolveThreadCount(defaults, 16) === 15);
checks.check('o tempo limite vira milissegundos e zero desliga', resolveTimeoutMs(defaults) === 10000 && resolveTimeoutMs({ ...defaults, timeoutSeconds: 0 }) === 0);
const damaged = { enabled: 'sim', threads: 99, timeoutSeconds: -4, maxQueued: 900 } as unknown as JobSettings;
const repaired = normalizeJobSettings(damaged);
checks.check('valores fora da faixa são trazidos para o limite', repaired.enabled && repaired.threads === MAX_JOB_THREADS && repaired.timeoutSeconds === 0 && repaired.maxQueued === 1024);
const empty = normalizeJobSettings({} as JobSettings);
checks.check('campos ausentes recebem o padrão', JSON.stringify(empty) === JSON.stringify(defaults));
const source = new Scene('Arena');
Object.assign(source.jobs, { enabled: false, threads: 6, timeoutSeconds: 45, maxQueued: 16384 } satisfies JobSettings);
const document = await serializeScene(source, { libraryDocumentForTerrainMaterial: () => null });
const { scene } = await deserializeScene(document, { materials: new MaterialLibrary(() => undefined, null) });
checks.check('a configuração de jobs sobrevive à gravação da cena', JSON.stringify(scene.jobs) === JSON.stringify(source.jobs));
delete document.json.environment.jobs;
const legacy = await deserializeScene(document, { materials: new MaterialLibrary(() => undefined, null) });
checks.check('cena antiga sem a configuração recebe o padrão', JSON.stringify(legacy.scene.jobs) === JSON.stringify(defaults));
checks.finish();
