export function baseMemberVisible(member: string, baseClass: string): boolean {
    if (!godotIsA(baseClass, 'Node'))
        return OBJECT_METHODS.has(member);
    const owner = MEMBER_OWNERS[member];
    return owner ? godotIsA(baseClass, owner) : true;
}
