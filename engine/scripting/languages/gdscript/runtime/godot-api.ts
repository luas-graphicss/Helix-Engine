export function isGodotNodeClass(name: string): boolean {
    return Object.prototype.hasOwnProperty.call(GODOT_NODE_CLASSES, name);
}
export function isGodotClass(name: string): boolean {
    return isGodotNodeClass(name) || GODOT_OBJECT_CLASSES.includes(name);
}
