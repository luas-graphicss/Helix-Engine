export function godotParentOf(name: string): string | null {
    if (name === 'Node' || name === 'Object')
        return null;
    const explicit = GODOT_PARENTS[name];
    if (explicit)
        return explicit;
    if (isGodotNodeClass(name))
        return name === 'Node3D' ? 'Node' : 'Node3D';
    if (GODOT_OBJECT_CLASSES.includes(name))
        return 'Object';
    return null;
}
export function godotIsA(name: string, ancestor: string): boolean {
    for (let current: string | null = name; current; current = godotParentOf(current))
        if (current === ancestor)
            return true;
    return false;
}
